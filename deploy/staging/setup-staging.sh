#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# One-time setup of the ICT Futures TEST SITE on an Ubuntu 24.04 server that
# already runs Apache 2.4 + Node 22 (Matt's web server).
#
#   sudo bash setup-staging.sh <domain> [branch] [port]
#   e.g. sudo bash setup-staging.sh ict-test.example.com staging 3460
#
# What it does (idempotent — safe to re-run):
#   1. Installs PostgreSQL if missing; creates DB + role ict_staging.
#   2. Creates system user ictstage; clones the repo to /opt/ict-staging/app
#      on <branch> (created from main on GitHub if it doesn't exist yet).
#   3. Writes /opt/ict-staging/app/.env with fresh random secrets (kept on re-run).
#   4. npm ci, prisma migrate deploy, seed instruments, production build.
#   5. systemd: ict-staging.service (Next.js on 127.0.0.1:<port>),
#      ict-staging-cycle.timer (autotrader + alerts every 30 min),
#      ict-staging-sync.timer (every 2 min: pull new commits on <branch>,
#      rebuild, migrate, restart — a failed build leaves the site unchanged).
#   6. Apache reverse-proxy vhost for <domain> + Let's Encrypt certificate.
# ---------------------------------------------------------------------------
set -euo pipefail

DOMAIN="${1:?usage: setup-staging.sh <domain> [branch] [port]}"
BRANCH="${2:-staging}"
PORT="${3:-3460}"
REPO_URL="https://github.com/mattriedl/ict-futures-platform.git"
BASE=/opt/ict-staging
APP="$BASE/app"
RUN_USER=ictstage
DB_NAME=ict_staging
DB_USER=ict_staging

log() { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }
[ "$(id -u)" = 0 ] || { echo "run as root (sudo)"; exit 1; }

log "PostgreSQL"
if ! command -v psql >/dev/null || ! systemctl list-unit-files | grep -q '^postgresql'; then
  DEBIAN_FRONTEND=noninteractive apt-get update -qq
  DEBIAN_FRONTEND=noninteractive apt-get install -y -qq postgresql postgresql-contrib
fi
systemctl enable --now postgresql
mkdir -p "$BASE"; chmod 750 "$BASE"
if [ ! -f "$BASE/.dbpass" ]; then openssl rand -hex 24 > "$BASE/.dbpass"; chmod 600 "$BASE/.dbpass"; fi
DB_PASS="$(cat "$BASE/.dbpass")"
sudo -u postgres psql -qtAc "SELECT 1 FROM pg_roles WHERE rolname='$DB_USER'" | grep -q 1 \
  || sudo -u postgres psql -qc "CREATE ROLE $DB_USER LOGIN PASSWORD '$DB_PASS'"
sudo -u postgres psql -qc "ALTER ROLE $DB_USER PASSWORD '$DB_PASS'"
sudo -u postgres psql -qtAc "SELECT 1 FROM pg_database WHERE datname='$DB_NAME'" | grep -q 1 \
  || sudo -u postgres psql -qc "CREATE DATABASE $DB_NAME OWNER $DB_USER"

log "User + code ($BRANCH)"
id "$RUN_USER" >/dev/null 2>&1 || useradd --system --home-dir "$BASE" --shell /usr/sbin/nologin "$RUN_USER"
if [ ! -d "$APP/.git" ]; then
  if git ls-remote --exit-code --heads "$REPO_URL" "$BRANCH" >/dev/null 2>&1; then
    git clone -q --branch "$BRANCH" "$REPO_URL" "$APP"
  else
    echo "branch '$BRANCH' not on GitHub yet — cloning main (push a '$BRANCH' branch to start previewing it)"
    git clone -q --branch main "$REPO_URL" "$APP"
    git -C "$APP" checkout -q -b "$BRANCH"
  fi
fi
chown -R "$RUN_USER:$RUN_USER" "$BASE"
chown root:root "$BASE/.dbpass"

log ".env"
if [ ! -f "$APP/.env" ]; then
  cat > "$APP/.env" <<ENV
# ICT Futures — TEST SITE. Secrets generated by setup-staging.sh. Never commit.
DATABASE_URL="postgresql://$DB_USER:$DB_PASS@127.0.0.1:5432/$DB_NAME?schema=public"
NEXTAUTH_URL="https://$DOMAIN"
NEXTAUTH_SECRET="$(openssl rand -base64 32)"
AUTOTRADE_SECRET="$(openssl rand -hex 24)"
APP_PORT=$PORT
NEXT_DIST_DIR=.build
# Optional — AI explanations (any OpenAI-compatible provider):
LLM_BASE_URL=""
LLM_API_KEY=""
LLM_MODEL=""
# Optional — email alerts (Gmail app password):
GMAIL_USER=""
GMAIL_APP_PASSWORD=""
EMAIL_FROM=""
ENV
fi
chown "$RUN_USER:$RUN_USER" "$APP/.env"; chmod 600 "$APP/.env"

log "Sync script"
install -m 755 "$APP/deploy/staging/ict-staging-sync.sh" /usr/local/bin/ict-staging-sync
sed -i "s#^BRANCH=.*#BRANCH=\"$BRANCH\"#; s#^APP=.*#APP=\"$APP\"#; s#^RUN_USER=.*#RUN_USER=\"$RUN_USER\"#" /usr/local/bin/ict-staging-sync

log "Install + build (first run takes a few minutes)"
/usr/local/bin/ict-staging-sync --force --no-restart

log "systemd units"
cat > /etc/systemd/system/ict-staging.service <<UNIT
[Unit]
Description=ICT Futures TEST SITE (Next.js on 127.0.0.1:$PORT)
After=network-online.target postgresql.service
Wants=network-online.target

[Service]
User=$RUN_USER
WorkingDirectory=$APP
EnvironmentFile=$APP/.env
Environment=NODE_ENV=production
Environment=NEXT_DIST_DIR=.build
ExecStart=/usr/bin/node node_modules/.bin/next start --hostname 127.0.0.1 --port $PORT
Restart=always
RestartSec=5
SyslogIdentifier=ict-staging

[Install]
WantedBy=multi-user.target
UNIT
cat > /etc/systemd/system/ict-staging-cycle.service <<UNIT
[Unit]
Description=ICT Futures TEST SITE scheduled cycle (autotrader + alerts)
After=ict-staging.service

[Service]
Type=oneshot
User=$RUN_USER
Environment=APP_DIR=$APP
ExecStart=$APP/deploy/ict-autotrade-local.sh
UNIT
cat > /etc/systemd/system/ict-staging-cycle.timer <<UNIT
[Unit]
Description=ICT Futures TEST SITE cycle every 30 minutes

[Timer]
OnCalendar=*-*-* *:19,49:00
Persistent=true

[Install]
WantedBy=timers.target
UNIT
cat > /etc/systemd/system/ict-staging-sync.service <<UNIT
[Unit]
Description=ICT Futures TEST SITE: deploy new commits on $BRANCH

[Service]
Type=oneshot
ExecStart=/usr/local/bin/ict-staging-sync
UNIT
cat > /etc/systemd/system/ict-staging-sync.timer <<UNIT
[Unit]
Description=Check GitHub for new $BRANCH commits every 2 minutes

[Timer]
OnBootSec=2min
OnUnitActiveSec=2min

[Install]
WantedBy=timers.target
UNIT
systemctl daemon-reload
systemctl enable --now ict-staging.service ict-staging-cycle.timer ict-staging-sync.timer
systemctl restart ict-staging.service

log "Apache vhost for $DOMAIN"
a2enmod -q proxy proxy_http headers rewrite ssl >/dev/null
mkdir -p "/var/www/$DOMAIN/acme"
cat > "/etc/apache2/sites-available/$DOMAIN.conf" <<VHOST
<VirtualHost *:80>
    ServerName $DOMAIN
    Alias /.well-known/acme-challenge/ /var/www/$DOMAIN/acme/.well-known/acme-challenge/
    <Directory /var/www/$DOMAIN/acme>
        Require all granted
    </Directory>
    RewriteEngine On
    RewriteCond %{REQUEST_URI} !^/\.well-known/acme-challenge/
    RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [R=301,L]
</VirtualHost>
VHOST
a2ensite -q "$DOMAIN" >/dev/null
apache2ctl configtest && systemctl reload apache2

if [ ! -d "/etc/letsencrypt/live/$DOMAIN" ]; then
  if [ -f /root/.secrets/cloudflare.ini ] && certbot certonly -n --agree-tos --register-unsafely-without-email \
       --dns-cloudflare --dns-cloudflare-credentials /root/.secrets/cloudflare.ini -d "$DOMAIN"; then
    echo "certificate issued via Cloudflare DNS"
  else
    certbot certonly -n --agree-tos --register-unsafely-without-email --webroot -w "/var/www/$DOMAIN/acme" -d "$DOMAIN"
  fi
fi

cat > "/etc/apache2/sites-available/$DOMAIN-ssl.conf" <<VHOST
<VirtualHost *:443>
    ServerName $DOMAIN
    SSLEngine on
    SSLCertificateFile /etc/letsencrypt/live/$DOMAIN/fullchain.pem
    SSLCertificateKeyFile /etc/letsencrypt/live/$DOMAIN/privkey.pem
    Header always set X-Robots-Tag "noindex, nofollow"
    ProxyPreserveHost On
    ProxyTimeout 300
    RequestHeader set X-Forwarded-Proto "https"
    ProxyPass        / http://127.0.0.1:$PORT/
    ProxyPassReverse / http://127.0.0.1:$PORT/
</VirtualHost>
VHOST
a2ensite -q "$DOMAIN-ssl" >/dev/null
apache2ctl configtest && systemctl reload apache2

log "Smoke test"
sleep 3
curl -s -o /dev/null -w "local  /login -> %{http_code}\n" "http://127.0.0.1:$PORT/login"
curl -s -o /dev/null -w "public /login -> %{http_code}\n" --resolve "$DOMAIN:443:127.0.0.1" "https://$DOMAIN/login"
echo
echo "Test site: https://$DOMAIN   (branch: $BRANCH, auto-deploys every 2 min)"
echo "Logs: journalctl -u ict-staging -f   |   sync: journalctl -u ict-staging-sync"
